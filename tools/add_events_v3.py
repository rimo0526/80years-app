def setup_sheet(ws, header):
    """ヘッダー行を装飾"""
    ws.append(header)
    fill = PatternFill("solid", fgColor="DCE6F1")
    font = Font(bold=True)
    for c in ws[1]:
        c.fill = fill
        c.font = font
        c.alignment = Alignment(horizontal="center")


def append_row(ws, row_data):
    """単純appendだが、bool→TRUE/FALSE文字列化"""
    out = []
    for v in row_data:
        if isinstance(v, bool):
            out.append("TRUE" if v else "FALSE")
        elif v is None:
            out.append(None)
        else:
            out.append(v)
    ws.append(out)


def main():
    wb = openpyxl.load_workbook(SRC)

    # 1. マイルストーンシート新設
    if "マイルストーン" in wb.sheetnames:
        del wb["マイルストーン"]
    ws_m = wb.create_sheet("マイルストーン")
    setup_sheet(ws_m, HEADER)
    for row in MILESTONES:
        append_row(ws_m, row)
    print(f"  マイルストーン: {len(MILESTONES)} 件追加")

    # 2. 暗号通貨を「収入連動イベント」に追加
    ws_in = wb["収入連動イベント"]
    for row in CRYPTO:
        append_row(ws_in, row)
    print(f"  暗号通貨（収入連動シート追加）: {len(CRYPTO)} 件追加")

    # 3. 異才解放を「ライフイベント」に追加
    ws_life = wb["ライフイベント"]
    for row in EX_UNLOCK:
        append_row(ws_life, row)
    print(f"  異才解放: {len(EX_UNLOCK)} 件追加")

    # 4. 時代別イベントを「時代イベント」に追加
    ws_era = wb["時代イベント"]
    for row in ERA_EVENTS:
        append_row(ws_era, row)
    print(f"  時代別: {len(ERA_EVENTS)} 件追加")

    # 5. 家族・キャリア追加を「ライフイベント」に
    for row in EXTRA:
        append_row(ws_life, row)
    print(f"  家族・キャリア追加: {len(EXTRA)} 件追加")

    total = len(MILESTONES) + len(CRYPTO) + len(EX_UNLOCK) + len(ERA_EVENTS) + len(EXTRA)
    print(f"\n  合計追加：{total} 件")

    wb.save(DST)
    print(f"\n  保存：{DST}")


if __name__ == "__main__":
    main()
